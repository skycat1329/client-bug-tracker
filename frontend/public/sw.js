// Service Worker for Assurance HR & Command Center PWA
const CACHE_NAME = 'assurance-v3';
const STATIC_ASSETS = [
  '/manifest.webmanifest',
  '/assurance-media-logo.jpg'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(STATIC_ASSETS);
    })
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
      );
    })
  );
  return self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  // 1. Pass through API calls directly to server (never cache dynamic API endpoints)
  if (event.request.url.includes('/api/')) {
    return;
  }

  // 2. Navigation / HTML requests: NETWORK-FIRST (so latest bundle and UI is ALWAYS served immediately)
  if (event.request.mode === 'navigate' || event.request.destination === 'document') {
    event.respondWith(
      fetch(event.request)
        .then((networkResponse) => {
          return networkResponse;
        })
        .catch(() => {
          return caches.match('/') || caches.match('/index.html');
        })
    );
    return;
  }

  // 3. Static hashed assets (css/js/images): Cache-first with network fallback
  event.respondWith(
    caches.match(event.request).then((cachedResponse) => {
      return cachedResponse || fetch(event.request);
    })
  );
});
